#!/usr/bin/env python3
"""Generate font.h: anti-aliased glyph bitmaps (ASCII + Vietnamese) for the framebuffer UI."""
import unicodedata
from PIL import Image, ImageDraw, ImageFont

REG = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

def vn_chars():
    s = set()
    bases = "aăâeêioôơuưy"
    tones = ["", "̀", "́", "̃", "̉", "̣"]
    for b in bases + bases.upper():
        for t in tones:
            s.add(unicodedata.normalize("NFC", b + t))
    s |= set("đĐ°·•→…–")
    return s

BASIC = set(chr(c) for c in range(32, 127)) | vn_chars()
BIG = set("0123456789%-.? ")

def build(name, path, size, chars):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    data = bytearray()
    glyphs = []
    for ch in sorted(chars, key=ord):
        adv = int(round(f.getlength(ch)))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            data += im.tobytes()
        glyphs.append((ord(ch), w, h, l, t, adv, off))
    out = [f"static const uint8_t {name}_data[] = {{" + ",".join(str(x) for x in data) + "};"]
    out.append(f"static const Glyph {name}_glyphs[] = {{")
    out += ["{%d,%d,%d,%d,%d,%d,%d}," % g for g in glyphs]
    out.append("};")
    out.append(f"static const Font {name} = {{{name}_glyphs, {len(glyphs)}, {name}_data, {asc}, {desc}}};")
    return "\n".join(out)

hdr = ["/* generated by gen_font.py (DejaVu fonts, Bitstream Vera license) */",
       "#include <stdint.h>",
       "typedef struct { uint32_t cp; int16_t w, h, xoff, yoff, adv; int32_t off; } Glyph;",
       "typedef struct { const Glyph *g; int n; const uint8_t *data; int asc, desc; } Font;"]
hdr.append(build("FONT_S", REG, 22, BASIC))
hdr.append(build("FONT_SB", BOLD, 22, BASIC))
hdr.append(build("FONT_M", BOLD, 30, BASIC))
hdr.append(build("FONT_L", BOLD, 150, BIG))
open("font.h", "w").write("\n".join(hdr) + "\n")
print("ok")
